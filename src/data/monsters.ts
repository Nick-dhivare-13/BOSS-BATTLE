/**
 * Returns the monster corresponding to a given id or index
 */
export function getMonsterById(id: string): Monster | undefined {
  return MONSTERS_STREAK_LIST.find((m) => m.id === id);
}

/**
 * Calculates which monster is currently qualified for a given user streak and task difficulty
 */
export function getEligibleMonsters(streakDays: number, difficulty?: string): Monster[] {
  return MONSTERS_STREAK_LIST.filter((m) => {
    const isStreakUnlocked = streakDays >= m.unlockStreakDays;
    if (!difficulty) return isStreakUnlocked;
    return isStreakUnlocked && m.allowedDifficulties.includes(difficulty as any);
  });
}
